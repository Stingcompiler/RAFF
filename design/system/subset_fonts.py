#!/usr/bin/env python3
"""Subset IBM Plex Sans Arabic into two families (Arabic script, Latin) (D-R0014, BACKLOG 142).

The Arabic block U+0600-06FF (letters, diacritics, Arabic-Indic digits, punctuation) and a
Latin set (letters, digits, Latin-1, common punctuation) are kept for the four weights, with
every layout feature so shaping and ligatures still work. Dropped: Arabic Supplement and
Extended-A, Quranic marks beyond the block, and the Presentation Forms (the browser shapes from
the base letters). A glyph outside these sets falls back to the system font.

    uv run --with fonttools --with brotli python3 design/system/subset_fonts.py

Writes frontend/src/fonts/ibm-plex-sans-arabic-{400,500,600,700}.woff2 and ibm-plex-sans-{…}.woff2 from the
@fontsource package, and frontend/src/styles/fonts.css with the matching @font-face rules.
"""

from __future__ import annotations

from pathlib import Path

from fontTools import subset

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "frontend/node_modules/@fontsource/ibm-plex-sans-arabic/files"
OUT = ROOT / "frontend/src/fonts"
CSS = ROOT / "frontend/src/styles/fonts.css"

WEIGHTS = (400, 500, 600, 700)
# Two families with disjoint ranges, so the browser never fetches both for one character:
# "IBM Plex Sans Arabic" holds the Arabic script, "IBM Plex Sans" the Latin and neutral signs
# (the Latin glyphs of the Arabic package are IBM Plex Sans).
FACES = {
    "arabic": ("IBM Plex Sans Arabic", "U+0600-06FF,U+200C-200F"),
    "latin": (
        "IBM Plex Sans",
        "U+0020-007E,U+00A0,U+00AB,U+00B0-00B1,U+00B5,U+00B7,U+00BB,U+00D7,U+00F7,"
        "U+2000-200B,U+2010-206F,U+2191,U+2193,U+2212,U+20AC",
    ),
}


def codepoints(spec: str) -> list[int]:
    out: list[int] = []
    for part in spec.split(","):
        lo, _, hi = part.removeprefix("U+").partition("-")
        out.extend(range(int(lo, 16), int(hi or lo, 16) + 1))
    return out


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    rules: list[str] = [
        "/* GENERATED by design/system/subset_fonts.py: IBM Plex Sans Arabic, subset (D-R0014). */"
    ]
    for weight in WEIGHTS:
        for name, (family, spec) in FACES.items():
            src = SRC / f"ibm-plex-sans-arabic-{name}-{weight}-normal.woff2"
            dst = OUT / (f"ibm-plex-sans-arabic-{weight}.woff2" if name == "arabic" else f"ibm-plex-sans-{weight}.woff2")
            options = subset.Options(flavor="woff2", layout_features=["*"], notdef_outline=True)
            font = subset.load_font(str(src), options)
            sub = subset.Subsetter(options)
            sub.populate(unicodes=codepoints(spec))
            sub.subset(font)
            subset.save_font(font, str(dst), options)
            print(f"{dst.name}: {dst.stat().st_size} bytes")
            rules.append(
                "@font-face {\n"
                f'  font-family: "{family}";\n'
                "  font-style: normal;\n"
                "  font-display: swap;\n"
                f"  font-weight: {weight};\n"
                f'  src: url("../fonts/{dst.name}") format("woff2");\n'
                f"  unicode-range: {spec};\n"
                "}"
            )
    CSS.write_text("\n\n".join(rules) + "\n")


if __name__ == "__main__":
    main()
